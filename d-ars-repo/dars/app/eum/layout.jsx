// app/eum/layout.jsx — 어르신 화면 묶음의 레이아웃 겸 **제품 브랜드 차단막**
//
// 고친 결함: 이 화면들은 `title` 만 어르신 것으로 덮어쓰고 있었다. 그런데 Next 의 `metadata` 는
// 레이아웃에서 페이지로 **상속**되고, 자식이 적지 않은 최상위 키는 부모 값이 그대로 내려간다.
// 루트 레이아웃(`app/layout.jsx`)은 운영 포털용으로 `openGraph`·`twitter`·`applicationName`·
// `appleWebApp` 을 선언해 두었으므로, 어르신 화면의 head 에는 제품 브랜드 제목과 사이트 이름이
// 그대로 실려 있었다.
//
// 왜 사소하지 않은가: **어르신은 링크를 문자로 받는다**(이 기능의 유일한 진입 경로다). 문자·메신저
// 앱은 링크를 받으면 그 주소를 긁어 `og:*` 로 **미리보기 카드**를 만들고, 어르신이 신청 화면보다
// 먼저 보는 것이 그 카드다. 거기 적혀 있던 것은 「이음 어르신 신청」이 아니라 운영 포털의 제목과
// 사이트 이름이었다 — 담당자가 보낸 링크인지 알아볼 단서가 없고, 「제품 화면을 어르신에게 노출하지
// 않는다」는 요건(로고·도입사례·요금표 표시 금지)이 화면 본문에서만 지켜지고 있었던 셈이다.
// 홈 화면에 추가했을 때의 이름(`appleWebApp`·`applicationName`)도 같다.
// 금지 문구는 테스트가 **화면 코드**에서 막고 있었지만 head 는 아무도 보지 않았다.
//
// 그래서 묶음 전체에 하나만 두어 단일 출처로 삼는다 — `/eum` · `/eum/senior` ·
// `/eum/senior/[token]` 과 경계 화면(오류·대기)이 모두 이 레이아웃 아래에 있다.
// 페이지가 자기 `title` 을 다시 적는 것은 그대로 둔다(같은 문구 · 가장 가까운 선언이 이긴다).
//
// 값을 지우는 대신 **어르신 문구로 덮어쓴다**: 최상위 키를 하나라도 적으면 그 키의 부모 값은
// 통째로 대체되므로, 덮어쓰기는 상속이 어떻게 합쳐지든 결과가 같다. 미리보기 카드를 없애지
// 않는 이유는 그 카드가 어르신에게 **도움이 되기 때문**이다 — 「이음 어르신 신청」이라고 적힌
// 카드는 담당자가 보낸 링크임을 알아보는 단서가 된다.
//
// 남겨 둔 상속은 `tests/eumseniorui.test.mjs` 가 사유와 함께 고정한다(`metadataBase` 등).
//
// ── 두 번째로 고친 결함: **문구만 덮고 파일은 그대로 매달려 있었다** ──────────────────────
// 위 대조는 루트 레이아웃의 `metadata` **export 키**를 전부 분류하게 한다. 그런데 head 로 들어오는
// 길은 그것만이 아니다 — Next 는 `app/` 의 **파일 규약**(`app/manifest.js`·`app/icon.svg`)도 긁어
// head 에 끼워 넣고, 그것들은 metadata export 에 적혀 있지 않아 **키 대조가 보지 못했다**.
// 그래서 지난 회차에 「알려진 한계」로 적어 둔 그대로 남아 있었고, 그 이유는
// "무엇으로 덮을지가 디자인 결정이라 자동화가 지어내지 않는다" 였다. 그 이유는 **덮는 것**에는
// 맞지만 **치우는 것**에는 맞지 않는다 — 어르신용 아이콘을 지어내는 것과, 포털 것을 매달지 않는
// 것은 다른 일이다. 치우는 쪽에는 지어낼 값이 없다.
//
// 무엇이 매달려 있었나:
//   · `rel="manifest"` → `app/manifest.js` 는 `name: 'D-ARS …'` · `start_url: '/dashboard'` ·
//     `theme_color: #be5535` · 제품 로고 아이콘을 담은 **운영 포털의 매니페스트**다. 안드로이드
//     크롬의 「홈 화면에 추가」는 이것을 읽으므로, 어르신 홈 화면에는 **제품 로고와 제품 이름**이
//     남고 그것을 누르면 **운영 포털 대시보드**가 열린다 — 신청 흐름 밖이고, 링크는 문자 안에
//     있고 수명은 5분이라 한 번 나가면 돌아오는 길을 스스로 찾지 못한다(경계 화면에서 「대시보드」
//     단추를 없앤 것과 **같은 문**이 head 에 남아 있었던 셈이다).
//     지난 회차가 `appleWebApp.title`(iOS 쪽 절반)만 어르신 문구로 덮었기 때문에, 두 절반이
//     서로 다른 말을 하고 있었다 — 그 불일치가 고침이 절반이었다는 증거다.
//   · `rel="icon"`(제품 로고) → 요건은 **로고 표시 금지**다. 탭·공유·홈 화면에서 보이는 그림이
//     제품 로고라면 그 요건은 화면 본문에서만 지켜지는 것이다. 어르신용 아이콘을 지어내지 않고
//     **아이콘을 선언하지 않는 쪽**을 고른다(빈 선언이 파일 규약의 끼어들기를 함께 막는다).
//   · `theme-color: #be5535`(주소창 색) → 제품 브랜드색이다. 이 화면의 바탕색은 이미 단일 출처에
//     있으므로(`EUM_COLORS.bg`) 주소창을 **화면과 같은 색**으로 맞춘다 — 지어낸 값이 아니다.

import { EUM_COLORS } from '@/lib/eumTheme';

const EUM_TITLE = '이음 어르신 신청';
const EUM_DESC = '이음 어르신 신청 화면입니다.';

export const metadata = {
  // 루트 템플릿('%s · 제품명')을 쓰지 않는다 — 어르신 화면에는 제품 브랜드를 노출하지 않는다.
  title: { absolute: EUM_TITLE },
  description: EUM_DESC,
  // 검색 색인 차단(루트와 같은 방침). 토큰이 든 주소가 색인되면 안 되므로 여기서도 명시한다.
  robots: { index: false, follow: false, googleBot: { index: false, follow: false } },
  // 문자·메신저가 읽는 미리보기 카드. 제품 이름·주소를 싣지 않는다
  // (부모의 `url`·`siteName` 까지 함께 대체된다 — 최상위 키 단위로 바뀌기 때문).
  openGraph: {
    type: 'website',
    locale: 'ko_KR',
    siteName: EUM_TITLE,
    title: EUM_TITLE,
    description: EUM_DESC,
  },
  twitter: { card: 'summary', title: EUM_TITLE, description: EUM_DESC },
  // 브라우저·홈 화면이 말하는 이름.
  applicationName: EUM_TITLE,
  appleWebApp: { title: EUM_TITLE, statusBarStyle: 'default' },
  // 아이콘을 선언하지 않는다 — 요건이 「로고 표시 금지」이고, 어르신용 아이콘은 디자인 결정이다.
  // **빈 선언**이어야 한다: Next 는 `metadata.icons` 가 비어 있을 때만 `app/icon.svg` 파일 규약을
  // 그 자리에 끼워 넣으므로, `null` 로 두면 제품 로고가 되살아난다(빌드 산출물로 확인).
  icons: { icon: [], apple: [] },
  // `manifest` 는 **여기서 끊을 수 없다** — 아래 주석 참조. 어르신 화면의 각 page 가 끊는다.
};

// 주소창·상단바 색. 이 화면의 바탕색과 같게 둔다(포털 브랜드색 #be5535 가 상속되고 있었다).
// width·initialScale 은 루트에서 그대로 상속한다 — 확대를 막는 설정은 어디에도 없다(저시력 요건).
export const viewport = {
  themeColor: EUM_COLORS.bg,
};

// ── `manifest` 만 이 파일에서 끊을 수 없는 이유(빌드 산출물로 확인한 사실) ──────────────
// Next 는 `app/` 의 파일 규약으로 찾아낸 정적 metadata 를 **그 폴더 바로 아래 세그먼트의
// 컴포넌트에 붙이고**, 병합 순서상 그것이 해당 세그먼트의 `metadata` export 보다 **뒤에**
// 적용된다(`manifest` 만 무조건 덮어쓴다 · icons 는 비어 있을 때만 끼워 넣는다).
// `app/manifest.js` 의 바로 아래 세그먼트가 하필 이 레이아웃이라, 여기에 `manifest: null` 을
// 적으면 **조용히 되살아난다** — 실제로 그렇게 적어 보고 산출물에서 `rel="manifest"` 가
// 그대로 남아 있는 것을 확인했다. 그래서 한 칸 더 아래(각 page)에서 끊는다.
// 「단일 출처」를 못 지키는 자리이므로, 빠뜨린 page 가 생기지 않게 테스트가 `app/eum/**` 의
// page 를 전부 긁어 대조한다(tests/eumseniorui.test.mjs).

// 레이아웃은 화면을 그리지 않는다 — 어르신 화면의 표현은 `senior/[token]/ui.jsx` 한 곳뿐이고,
// 여기에 머리말·꼬리말을 더하면 그 단일 출처가 둘로 갈라진다(버튼 4개 이내 요건도 함께 흔들린다).
export default function EumLayout({ children }) {
  return <>{children}</>;
}
