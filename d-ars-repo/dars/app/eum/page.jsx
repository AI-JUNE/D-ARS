// app/eum/page.jsx — 링크가 더 짧게 잘려 열린 경우(`/eum`)의 안내
//
// 왜 필요한가: 바로 아래 `senior/page.jsx` 가 받는 주소(`/eum/senior`)와 **같은 사고**다.
// 어르신은 링크를 문자로 받고, 문자 앱은 긴 주소를 줄바꿈으로 자른다 — 어디서 잘리느냐에 따라
// 눌리는 주소가 `/eum/senior` 일 수도, 한 칸 더 짧은 `/eum` 일 수도 있다. 앞의 것은 어르신 안내로
// 받아 두었는데 뒤의 것은 Next 의 unmatched 처리로 **루트 404 화면**(운영 포털)으로 갔다.
//
// 이 주소를 「알려진 한계」에 "세그먼트별 not-found 로는 받을 수 없다"고 적어 두었던 것은
// 사실이지만(불일치 경로는 루트 not-found 가 받는다), 그래서 **고칠 수 없다**는 결론은 틀렸다 —
// 한 칸 아래에서 이미 쓴 수단이 그대로 있었다. 주소를 **매칭되게** 만들면(이 파일) 루트 404 로
// 가지 않는다. 포털 404 화면은 손대지 않으므로 운영자 쪽도 그대로다.
//
// 어르신이 보던 것: 14px 글자에 커다란 「404」, 그리고 「홈으로」·「대시보드」 단추 두 개 —
// 어르신에게 404 는 아무 뜻이 없고, 두 단추는 신청 흐름 **밖**의 제품 화면으로 데려간다.
// 링크는 문자 안에 있고 수명은 5분이라, 한 번 나가면 돌아오는 길을 스스로 찾지 못한다.
//
// 잘못된 링크와 **같은 말**을 한다(`EUM_TOKEN_MESSAGE.missing` 단일 출처) — 링크가 온전하지
// 않으니 담당자에게 다시 청하면 된다는 것. 어르신이 스스로 할 수 있는 일은 그것뿐이라 단추는 두지
// 않는다. 토큰을 다루지 않는다 — 검증할 것도, 소진할 것도 없다(판정은 `senior/[token]` 한 곳뿐).

import { tokenMessage } from '@/lib/eumMessage';
import { Notice, EUM_NOTICE_FOOT } from './senior/[token]/ui.jsx';

export const metadata = {
  // 루트 템플릿('%s · 제품명')을 쓰지 않는다 — 어르신 화면에는 제품 브랜드를 노출하지 않는다.
  title: { absolute: '이음 어르신 신청' },
  // 운영 포털 매니페스트(`app/manifest.js` — 이름·시작 주소·아이콘이 전부 포털)를 매달지 않는다.
  // 왜 레이아웃이 아니라 여기인지는 `app/eum/layout.jsx` 아래쪽 주석 참조(파일 규약이 덮는다).
  manifest: null,
};

export default function EumRootNoLink() {
  // 마무리 문구는 **이 화면에서 참인 것**만 말한다. 예전에는 기본값("이 화면은 안전을 위해
  // 5분이 지나면 닫힙니다")이 조용히 붙었는데, 이 주소는 토큰이 없는 정적 페이지라 닫히지
  // 않는다 — 애초에 열린 적 없는 5분을 두고 한 말이었다(ui.jsx 의 EUM_NOTICE_FOOT 참조).
  return <Notice title="링크를 열 수 없습니다" body={tokenMessage('missing')} foot={EUM_NOTICE_FOOT.link} />;
}
