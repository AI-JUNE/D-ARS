// app/eum/[...rest]/page.jsx — `/eum` 아래 **어긋난 주소 전부**의 안내
//
// 왜 필요한가: 10회차에 `/eum/senior`(토큰이 없는 주소)와 `/eum`(한 칸 더 짧은 주소)을
// 어르신 안내로 받아 두고, 남은 경우를 「알려진 한계」에 이렇게 적었다 —
//   "그보다 더 어긋난 주소(`/eu`·`/eum/sen` 처럼 세그먼트 중간에서 잘린 경우)는 여전히 루트
//    404 화면으로 간다. **잘릴 수 있는 지점마다 라우트를 깔 수는 없고**, 포털 404 를 어르신
//    문구로 바꾸면 운영자 쪽이 나빠지므로 그 경로는 고치지 않고 여기 적어 둔다."
// 앞의 사실은 맞았지만 결론은 또 틀렸다 — **지점마다 깔 필요가 없었다.** 세그먼트 하나를
// 캐치올로 받으면 `/eum` 아래의 어긋난 주소가 **몇 가지든 한 라우트로** 들어온다. 10회차가
// "세그먼트 not-found 로는 받을 수 없다 → 고칠 수 없다" 를 "주소를 매칭되게 만들면 된다" 로
// 뒤집은 것과 **같은 모양**이고, 쓰는 수단도 그때와 같다(세그먼트 page).
//
// 무엇이 걸리나: 문자 앱은 긴 주소를 줄 끝에서 자르고, 어디서 자르는지는 우리가 고를 수 없다.
// 토큰 안에서 잘리면 `[token]` 이 받아 안내하지만(가장 흔한 경우 — 토큰이 가장 길다),
// **「senior」 글자 안에서** 잘리면 `/eum/s`·`/eum/se`·`/eum/sen`·`/eum/seni`·`/eum/senio` 가 되고
// 그 다섯은 지금까지 전부 운영 포털의 404 로 갔다 — 14px 글자에 커다란 「404」, 그리고
// 「홈으로」·「대시보드」 단추. 어르신에게 404 는 아무 뜻이 없고, 두 단추는 신청 흐름 **밖**의
// 제품 화면으로 데려간다. 링크는 문자 안에 있고 수명은 5분이라 한 번 나가면 돌아오는 길을
// 스스로 찾지 못한다(경계 화면에서 그 단추를 없앤 것과 **같은 문**이 여기 남아 있었다).
//
// 이 라우트가 받지 **않는** 것: `/eum` 자체(세그먼트가 0개 — 바로 위 `page.jsx` 가 받는다) ·
// `/eum/senior`·`/eum/senior/<토큰>`(더 구체적인 라우트가 이긴다). 그리고 `/eum` **앞에서**
// 잘린 주소(`/e`·`/eu`)는 여전히 루트 404 다 — 그쪽은 어르신 화면의 주소가 아니라 포털의
// 주소 공간이고, 거기에 어르신 화면을 깔면 운영자 쪽이 나빠진다(「알려진 한계」에 남긴다).
//
// 잘못된 링크와 **같은 말**을 한다(lib/eumMessage 단일 출처) — 어르신이 스스로 할 수 있는 일은
// 담당자에게 다시 청하는 것뿐이라 단추는 두지 않는다. 토큰을 다루지 않는다(판정은
// `senior/[token]/page.jsx` 한 곳뿐이고, 여기 온 주소에는 토큰이라고 믿을 것이 없다).
// 들어온 주소를 화면에 **되비추지 않는다** — 주소를 그리면 그 자리가 곧 반사형 삽입 지점이 되고,
// 어르신에게 자기가 누른 긴 주소는 읽을 수 있는 정보가 아니다.

import { panelAsk, panelTitle } from '@/lib/eumMessage';
import { Notice, EUM_NOTICE_FOOT } from '../senior/[token]/ui.jsx';

// head 는 `app/eum/layout.jsx` 가 단일 출처다 — 여기 적는 것은 레이아웃이 말할 수 없는 것뿐이고,
// 레이아웃이 이미 선언한 키를 다시 적으면 그 값을 **통째로** 밀어낸다(`senior/[token]/page.jsx`
// 주석 참조: 그렇게 적힌 `robots` 가 `googleBot` 지시를 조용히 지우고 있었다).
export const metadata = {
  // 루트 템플릿('%s · 제품명')을 쓰지 않는다 — 어르신 화면에는 제품 브랜드를 노출하지 않는다.
  // (문구를 상수로 빼지 않는 이유: head 대조는 **소스에 적힌 글자**를 읽어 브랜드 누출을
  //  판정한다. import 한 이름으로 바꾸면 그 대조가 아무 글자도 보지 못해 조용히 통과한다.)
  title: { absolute: '이음 어르신 신청' },
  // 운영 포털 매니페스트(`app/manifest.js` — 이름·시작 주소·아이콘이 전부 포털)를 매달지 않는다.
  // 왜 레이아웃이 아니라 여기인지는 `app/eum/layout.jsx` 아래쪽 주석 참조(파일 규약이 덮는다).
  manifest: null,
};

// 「senior」 글자 안에서 잘린 다섯은 **미리 그려 둔다.** 이유는 둘이다 — 링크 수명이 5분이라
// 서버를 한 번 덜 거치는 쪽이 낫고(이 주소를 누른 어르신은 이미 한 번 헛걸음한 사람이다),
// 미리 그린 HTML 이 있으면 head 불변식(포털 매니페스트·아이콘이 매달리지 않는다)을 **빌드
// 산출물로 확인**할 수 있다. 목록은 세그먼트 이름에서 **파생**한다 — 손으로 적으면 경로가
// 바뀌는 날 썩는다. 그 밖의 주소는 그대로 서버가 그린다(dynamicParams 기본값).
const CUT_IN = 'senior';

export function generateStaticParams() {
  // 's' … 'senio' — 마지막(=실제 세그먼트 이름)은 더 구체적인 라우트가 받으므로 뺀다.
  return [...CUT_IN].slice(0, -1).map((_, i) => ({ rest: [CUT_IN.slice(0, i + 1)] }));
}

export default function EumWrongPath() {
  // 이 화면은 닫히지 않는다(토큰이 없다) — 마무리 문구는 「링크를 끝까지 눌러 주세요」다.
  // 본문도 제목과 **같은 사유**에서 온다 — 만료 화면만 조건절을 들어야 해서 갈린 자리이고
  // (lib/eumMessage 의 EUM_PANEL_ASK_EXPIRED), 토큰이 없는 이 화면의 할 일은 무조건 하나다.
  return <Notice title={panelTitle('missing')} body={panelAsk('missing')} foot={EUM_NOTICE_FOOT.link} />;
}
