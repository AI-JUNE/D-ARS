// ── 만료 임박 경고는 **그 화면에서 할 수 있는 일**을 말한다 ─────────────────
//
// 고친 결함: 이 경고는 문장 **한 벌**이었고(`lib/eumCountdown.EUM_SOON_MESSAGE`), 신청 흐름
// 1~3단계 어디서나 같은 말을 했다 — 「잠시 후 링크가 만료됩니다. **지금 고르신 것을 신청해
// 주세요**」. 그 뒤 문장이 맞는 자리는 **확인 화면(3단계) 하나뿐**이다.
//   · 1단계에서는 **고른 것이 없다.** 「지금 고르신 것」이 가리키는 것이 화면에 없고, 신청할
//     단추도 없다(선택지 네 개뿐이다). 남은 1분 안에 할 일은 두 번 고르고 확인 화면까지
//     가는 것인데, 경고는 그 말을 하지 않는다.
//   · 2단계에서는 활동만 골랐다. 그 상태로 「신청」을 찾으면 화면에 없다.
// 즉 **되돌릴 길을 가리키는 문장이 그 화면에 없는 것을 가리키고** 있었다 — 11회차가
// 「아래 단추」로 없앤 것과, 8회차가 마무리 문구에서 없앤 것(「5분이 지나면 닫힙니다」가
// 만료된 사람과 잘린 링크 화면에서 거짓이었다)과 **같은 모양**이다. 그리고 그 셋의 공통
// 원인도 같다: **한 문장이 아무 조건 없이 모든 자리에 붙는다.**
// 하필 이 경고는 **들리는 것이 존재 이유 전부**다(15회차) — 눈으로 보는 어르신에게는 옆의
// 초 숫자가 이미 말해 주고, 이 문장이 더 보태는 것은 「그래서 지금 무엇을 하라」 한 마디다.
// 그 한 마디가 틀린 자리가 셋 중 둘이었다.
//
// 그래서 앞 토막(무슨 일이 일어나는가)은 한 벌로 두고, 뒤 토막(지금 할 일)만 단계별
// 등록부에 둔다 — EUM_PANEL_TITLE·EUM_PANEL_ASK 를 제목·본문으로 나눠 쓰는 것과 같은 꼴이다.
//
// 앞 토막은 **바로 다음에 보게 되는 화면의 제목과 같은 낱말**이어야 한다(13회차): 경고를
// 듣고 기다린 어르신이 만나는 화면의 제목이 「링크가 만료되었습니다」이기 때문이다. 시제가
// 달라(됩니다/되었습니다) 제목을 그대로 끼울 수는 없으므로 — 글자를 바꿔 끼우는 것은 제목이
// 달라지는 날 뜻이 어긋나는 쪽으로 조용히 통과한다 — 문장은 여기 적고 **낱말이 겹치는지를
// 테스트가 양쪽에서 대조한다**(「닫힙니다」가 되살아나면 실패한다).
// 초 숫자는 여기 넣지 않는다: 이 문장은 한 번만 낭독돼야 하고, 매초 바뀌는 숫자를 섞으면
// 1초마다 말을 끊고 처음부터 다시 읽는다(초 숫자는 화면이 aria-hidden 으로 따로 붙인다).
export const EUM_SOON_LEAD = '잠시 후 링크가 만료됩니다';

export const EUM_SOON_NEXT = {
  // 1단계 — 아직 아무것도 고르지 않았다. 남은 일이 둘이라는 것까지 말해 준다.
  1: '활동과 시간을 고르고 신청해 주세요',
  // 2단계 — 활동은 골랐다. 남은 것은 시간 하나다.
  2: '시간을 고르고 신청해 주세요',
  // 3단계 — 고른 것이 화면에 있고 신청 단추도 있다. 예전의 그 문장이 맞는 **유일한** 자리다.
  3: '지금 고르신 것을 신청해 주세요',
};

// 지금 단계에서 할 일을 붙인 경고 한 문장.
//
// 모르는 단계는 **앞 토막만** 돌려준다(빈 문자열이 아니다). 여기서 침묵을 고르지 않는 이유:
// 앞 토막은 어느 단계에서나 참이고(링크가 곧 만료된다), 그것을 듣지 못하는 것이 이 경고에서
// 가장 비싼 결과다 — 보이지 않는 어르신은 남은 1분을 **모르는 채** 고르다가 화면이 만료
// 패널로 뒤집히는 것을 맞는다(15회차가 영역을 미리 두어 겨우 들리게 만든 그 문장이다).
// 기본값을 두지 않는 EUM_NOTICE_FOOT·EUM_PRIOR_TAIL 과 방향이 다른 것은, 그 둘은 **틀린
// 말이 조용히 붙는 것**이 위험이었고 여기는 **참인 말이 조용히 사라지는 것**이 위험이기
// 때문이다. 어느 쪽이든 지어내지 않는다는 선은 같다.
// 프로토타입 이름을 걸러 내는 이유는 위 tokenMessage 와 같다.
export function soonMessage(step) {
  const next = EUM_SOON_NEXT[step];
  return typeof next === 'string' && next ? `${EUM_SOON_LEAD}. ${next}.` : `${EUM_SOON_LEAD}.`;
}
