// lib/eumMessage.js — 어르신 화면 문구의 단일 출처(**클라이언트 안전**)
//
// 왜 떼어 냈나: 이 문장들은 `lib/eumToken.js` 안에 있었다. 그 파일은 서명 비밀을 읽고
// HMAC 을 계산하므로 **클라이언트 번들에 들어가서는 안 된다** — 그래서 브라우저에서 도는
// `SeniorFlow` 는 같은 문장을 **손으로 적어** 쓰고 있었다.
//   · 만료 안내: 「링크가 만료되었습니다. 담당자에게 다시 요청해 주세요」 — 글자까지 같은 사본.
//   · 401 안내: 「링크가 올바르지 않습니다. 담당자에게 다시 요청해 주세요**.**」 — 마침표 하나가
//     더 붙은 **같은 문장의 두 번째 판본**이었다. 어르신이 어느 화면을 밟느냐에 따라 끝이 달랐다.
// EUM_INTEGRATION.md 는 줄곧 "문구는 `EUM_TOKEN_MESSAGE` 단일 출처" 라고 적었지만 그것은
// **서버 쪽 세 화면에서만** 참이었다 — 또 하나의 "코드보다 앞선 서술"이다.
//
// 고르는 길은 둘이었다: ① 화면이 `lib/eumToken` 을 import 한다(= 비밀값·HMAC 이 브라우저
// 번들로 따라 들어간다 — 해서는 안 되는 일이다) ② **문구 표만** 비밀을 모르는 자리로 뗀다.
// 둘째를 골랐다. 이 파일에는 문자열뿐이고, 암호·환경변수·입출력이 한 줄도 없다
// (tests/eummessage.test.mjs 가 그것을 검사한다 — 비밀을 읽는 코드가 들어오면 실패한다).

// 토큰 검증 실패 사유별 안내문(사유 이름은 lib/eumToken.verifyEumToken 의 `reason` 과 같다).
//
// 왜 만료만 다른 문장인가: 만료는 **담당자가 새 링크를 보내면 해결되는 상태**이고, 나머지는
// 링크 자체가 잘못된 상태다. 어르신이 다음에 할 일이 같아 보여도(담당자에게 연락) 무엇이
// 잘못됐는지는 다르게 말해야 한다 — 「만료」라고 들은 어르신은 늦었구나 알고, 「올바르지
// 않다」고 들은 어르신은 링크가 잘려 왔는지 다시 본다.
//
// 문장 끝에 마침표를 두지 않는다. 안내 패널(Notice)의 본문 한 줄로 그려지는 문장이고,
// 같은 자리의 다른 문장들도 마침표가 없다 — 섞이면 화면마다 끝이 달라진다.
export const EUM_TOKEN_MESSAGE = {
  expired: '링크가 만료되었습니다. 담당자에게 다시 요청해 주세요',
  signature: '링크가 올바르지 않습니다. 담당자에게 다시 요청해 주세요',
  malformed: '링크가 올바르지 않습니다. 담당자에게 다시 요청해 주세요',
  missing: '링크가 올바르지 않습니다. 담당자에게 다시 요청해 주세요',
};

// 모르는 사유는 **가장 보수적인 안내**(잘못된 링크)로 떨어진다 — 빈 문자열을 돌려주면
// 화면이 아무 말도 하지 않는 상태가 되고, 그것이 이 함수가 막아야 하는 결과다.
// 등록부에 **실제로 적힌 문장**일 때만 쓴다: `EUM_TOKEN_MESSAGE[reason]` 을 그대로 믿으면
// 'constructor'·'__proto__' 같은 이름이 프로토타입의 값을 끌어와 참처럼 보이고,
// 그것이 그대로 화면에 그려진다(어르신이 읽을 수 없는 글자가 안내문 자리에 앉는다).
export function tokenMessage(reason) {
  const msg = EUM_TOKEN_MESSAGE[reason];
  return typeof msg === 'string' ? msg : EUM_TOKEN_MESSAGE.malformed;
}

// ── 제출이 되지 않았을 때의 안내(알림 자리) ────────────────────────────────
//
// 고친 결함: 이 다섯 문장은 `SeniorFlow` 안에 **손으로 적혀** 있었고, 그래서 두 가지가
// 아무 신호 없이 들어와 있었다.
//
//   (1) **자리를 가리키는 말.** 둘이 「**아래** 단추를 한 번 더 눌러 주세요」였다. 그런데 그
//       안내는 주버튼보다 **위**에 그려졌으므로, 안내가 생기는 순간 가리키던 단추를 자기가
//       아래로 밀어냈다 — 어르신이 외워 둔 자리에 더는 단추가 없다. 그리고 「아래」는
//       **눈에만 뜻이 있는 말**이다(스크린리더에 위·아래는 없고, 그 순간 포커스는 이미 그
//       단추에 남아 있다 — 8회차의 `aria-disabled`). 나머지 셋은 처음부터 자리를 가리키지
//       않았다(「연결을 확인하고 다시 눌러 주세요」·「잠시 후 다시 눌러 주세요」) — 같은
//       자리의 다섯 문장이 두 규칙으로 갈려 있었던 셈이다.
//   (2) **문장 끝.** 위 `EUM_TOKEN_MESSAGE` 는 마침표로 끝내지 않는다. 그런데 같은 알림
//       자리에 그려지는 이 문장들은 전부 마침표로 끝났고, 그 자리에는 401 안내
//       (`tokenMessage('signature')`)도 함께 온다 — 어르신이 어느 실패를 만나느냐에 따라
//       문장의 끝이 달랐다. 9회차가 없앤 「마침표가 하나 더 붙은 두 번째 판본」이 **같은
//       자리에 네 벌** 남아 있었다.
//
// 그래서 문장을 표로 모으고 규약을 테스트가 들게 한다(tests/eummessage.test.mjs) —
// 자리를 가리키는 낱말이 없고, 끝은 위 표와 같은 한 가지다. 자리를 가리키지 않아도 뜻이
// 서는 이유는 안내가 **주버튼 바로 아래**에 붙고(ui.jsx 의 Alert · 더는 단추를 밀어내지
// 않는다) 키보드·스크린리더에서는 포커스가 그 단추에 남아 있기 때문이다.
export const EUM_SUBMIT_MESSAGE = {
  // 고른 것이 사라진 채 제출에 닿았다 — 되돌릴 길은 처음부터 다시 고르는 것뿐이다.
  // 이 안내만 **고르는 화면(1단계)** 에 그려진다(나머지는 확인 화면).
  selection: '선택이 저장되지 않았습니다. 처음부터 다시 골라 주세요',
  // 브라우저가 오프라인이라고 말한 경우 — 눌러도 네트워크를 두드리지 않는다.
  offline: '인터넷 연결이 끊겼습니다. 연결을 확인하고 다시 눌러 주세요',
  // 응답이 오지 않았거나 상한(8초)을 넘겨 우리가 끊은 경우. 다시 눌러도 안전하다 —
  // 첫 요청이 서버에 닿았다면 409 로 돌아와 **완료 화면**이 된다.
  unreachable: '연결이 원활하지 않습니다. 한 번 더 눌러 주세요',
  // 한도에 걸린 경우(429). 지금 할 수 있는 일은 잠시 기다리는 것뿐이다.
  tooMany: '잠시 후 다시 눌러 주세요',
  // 그 밖에 서버가 받아 주지 않은 경우 — 무엇이 잘못됐는지 모를 때의 가장 보수적인 안내다.
  rejected: '신청을 접수하지 못했습니다. 한 번 더 눌러 주세요',
};

// 모르는 사유는 `rejected`(접수되지 않았다는 사실만 말한다)로 떨어진다. 빈 문자열을
// 돌려주면 실패한 제출이 **아무 말도 없이** 끝나고, 그것이 이 함수가 막아야 하는 결과다.
// 프로토타입 이름을 걸러 내는 이유는 위 tokenMessage 와 같다.
export function submitMessage(reason) {
  const msg = EUM_SUBMIT_MESSAGE[reason];
  return typeof msg === 'string' ? msg : EUM_SUBMIT_MESSAGE.rejected;
}

// ── 접수가 끝났다는 사실 ───────────────────────────────────────────────────
//
// 고친 결함: 「이미 접수됐다」는 사실을 보여 주는 화면은 둘이다 — 링크를 **다시 열었을 때**
// (진입 안내 · `[token]/page.jsx`)와 제출이 **409 로 돌아왔을 때**(완료 화면 · `SeniorFlow`).
// 9회차에 그 둘을 「단일 출처」로 묶었다고 적었고 테스트 이름도 「진입 안내와 완료 화면의
// 문구는 단일 출처다」였지만, 그 테스트가 실제로 대조한 것은 **뒤에 붙는 두 힌트**뿐이었다.
// 정작 두 화면의 **본문**은 각자 적혀 있었고, 그래서 서로 다른 말을 했다.
//   · 완료 화면 → 「이미 접수된 신청이 있습니다. 담당자가 곧 전화로 안내해 드립니다.」
//     (할 일이 없다는 뜻 — 맞는 말이다)
//   · 진입 안내 → 「이미 신청이 접수된 링크입니다. **담당자에게 문의해 주세요**」
//     (할 일이 있다는 뜻 — 틀린 말이다)
// 틀린 쪽의 대가가 이 과제가 줄곧 막아 온 것이다. 그 화면은 바로 아래에서 「바꾸고 싶으시면
// 담당자에게 말씀해 주세요」(조건부)와 「이제 이 화면을 닫으셔도 됩니다」(할 일 없음)를
// 이어서 말한다 — 한 화면이 **세 가지 다른 말**을 하고, 그중 맨 위의 것만 무조건 전화를
// 걸라고 한다. 신청이 멀쩡히 접수된 어르신이 담당자에게 전화하면 담당자는 **새 링크**를
// 보내고, 새 링크는 소진 키가 달라 재신청이 실제로 통한다 → 명단에 두 건. 9회차가 힌트
// 한 줄로 막은 그 중복을, **같은 화면의 본문**이 그대로 만들고 있었다.
//
// 그래서 사실을 말하는 문장도 한 벌로 묶는다. `lib/eumConsume.EUM_CONSUME_MESSAGE.used` 가
// 이 표를 가리키므로 진입 안내·409 응답·완료 화면이 전부 같은 문장을 쓴다.
export const EUM_DONE_MESSAGE = {
  // 방금 접수됐다.
  accepted: '신청이 접수되었습니다. 담당자가 곧 전화로 안내해 드립니다',
  // 이미 접수돼 있었다(같은 링크를 다시 열었을 때 · 제출이 409 로 돌아왔을 때).
  // 「문의해 주세요」라고 말하지 않는다 — 접수는 끝났고 어르신이 할 일이 없다.
  // 바꾸고 싶은 경우에만 담당자에게 말하면 되고, 그것은 뒤따르는 힌트가 조건부로 말한다
  // (lib/eumConsume.EUM_CONSUME_CHANGE_HINT).
  already: '이미 신청이 접수되었습니다. 담당자가 곧 전화로 안내해 드립니다',
};

// ── 깨졌을 때·기다릴 때 보이는 화면의 문구 ─────────────────────────────────
//
// 고친 결함: 이 여섯 문구는 `app/eum/error.jsx`·`app/eum/loading.jsx` 안에 **손으로 적혀**
// 있었다. 11회차가 제출 실패 다섯 문장을 이 표로 옮길 때 그 두 화면은 "회당 2~3건" 때문에
// 남겨 두었는데, 하필 오류 화면의 본문이 **그 회차에 없앤 바로 그 낱말**이었다 —
// 「잠시 뒤 **아래** 단추를 눌러 주세요.」
//   · 「아래」는 눈에만 뜻이 있는 말이다. 스크린리더에 위·아래는 없다.
//   · 그리고 이제 그 화면은 **제목으로 포커스를 옮긴다**(app/eum/error.jsx) — 그 순간
//     들리는 것은 제목이고, 단추는 「아래」가 아니라 **이름**으로 가리켜야 찾을 수 있다.
//   · 끝이 마침표였다. 이 화면군의 본문 문장은 마침표로 끝내지 않는다(위 두 표와 같은 규약).
// 단추 이름을 문장에 손으로 또 적으면 이름과 안내가 갈라질 수 있으므로, 본문은 단추 이름을
// **끼워서 짓는다**(한 벌).
