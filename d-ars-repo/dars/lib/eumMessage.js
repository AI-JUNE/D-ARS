// lib/eumMessage.js — 어르신 화면 문구의 단일 출처(**클라이언트 안전**)
//
// 왜 떼어 냈나: 이 문장들은 `lib/eumToken.js` 안에 있었다. 그 파일은 서명 비밀을 읽고
// HMAC 을 계산하므로 **클라이언트 번들에 들어가서는 안 된다** — 그래서 브라우저에서 도는
// `SeniorFlow` 는 같은 문장을 **손으로 적어** 쓰고 있었다.
//   · 만료 안내: 「링크가 만료되었습니다. 담당자에게 다시 요청해 주세요」 — 글자까지 같은 사본.
//   · 401 안내: 「링크가 올바르지 않습니다. 담당자에게 다시 요청해 주세요**.**」 — 마침표 하나가
//     더 붙은 **같은 문장의 두 번째 판본**이었다. 어르신이 어느 화면을 밟느냐에 따라 끝이 달랐다.
// EUM_INTEGRATION.md 는 줄곧 "문구는 `EUM_TOKEN_MESSAGE` 단일 출처" 라고 적었지만 그것은
// **서버 쪽 세 화면에서만** 참이었다 — 또 하나의 "코드보다 앞선 서술"이다.
//
// 고르는 길은 둘이었다: ① 화면이 `lib/eumToken` 을 import 한다(= 비밀값·HMAC 이 브라우저
// 번들로 따라 들어간다 — 해서는 안 되는 일이다) ② **문구 표만** 비밀을 모르는 자리로 뗀다.
// 둘째를 골랐다. 이 파일에는 문자열뿐이고, 암호·환경변수·입출력이 한 줄도 없다
// (tests/eummessage.test.mjs 가 그것을 검사한다 — 비밀을 읽는 코드가 들어오면 실패한다).

// ── 화면이 손으로 적던 이름과 제목 ─────────────────────────────────────────
//
// 고친 결함: 이 표가 문구의 단일 출처가 된 뒤에도 **제목과 머리말은 화면 파일마다 손으로
// 적혀 있었다.** 그래서 아무도 그 둘을 서로 대조하지 않았고, 그 사이 안내 패널은 **같은
// 문장을 두 번** 말하고 있었다 —
//   · 만료 패널: 제목 「링크가 만료되었습니다」 / 본문 「링크가 만료되었습니다. 담당자에게
//     다시 요청해 주세요」. 제목이 본문의 첫 문장과 **글자까지 같다**.
//   · 잘린 링크 패널: 제목 「링크를 열 수 없습니다」 / 본문 「링크가 올바르지 않습니다. …」.
//     글자는 다르지만 같은 사실을 두 번 말하고, 하필 **무엇이 잘못됐는지를 말하는 쪽**(본문)이
//     제목에 밀려 두 번째로 온다.
// 왜 사소하지 않은가: 이 패널은 전환과 함께 **제목으로 포커스가 옮겨 간다**(11회차). 그래서
// 스크린리더로 듣는 어르신은 제목을 듣고, 이어 읽는 본문에서 **방금 들은 문장을 한 번 더**
// 듣는다 — 「고른 것 표시(✓)를 aria-hidden 으로 가린」 것과 같은 이유로 피해야 하는 중복이고
// (같은 사실을 두 번 낭독하지 않는다), 저시력 어르신에게는 24px 이상 글자 두 줄이 같은 말을
// 하는 화면이다. 되돌릴 단추가 없는 화면에서 읽을 것이 둘 중 하나는 쓸모가 없었다.
//
// 그래서 제목을 표로 올리고, **본문은 제목이 말하지 않은 것만** 말한다(다음에 할 일).
// 두 문장이 같은 토막에서 나오므로 한쪽만 고쳐져 갈라지는 길이 없고, 재발 방지는
// 「제목이 본문에 그대로 들어 있으면 실패」로 못박는다(tests/eummessage.test.mjs).
export const EUM_KICKER = '이음 어르신 신청';

// 안내 패널의 제목 — **무엇이 잘못됐는가**(또는 지금 어떤 상태인가).
export const EUM_PANEL_TITLE = {
  expired: '링크가 만료되었습니다',
  // 잘못된 링크·문자에서 잘린 링크. 예전 제목은 「링크를 열 수 없습니다」였는데, 그것은
  // 결과만 말하고 이유를 말하지 않았다 — 이유는 본문의 첫 문장에 있었다. 제목이 그 자리를
  // 가져오고 본문은 할 일만 남긴다.
  link: '링크가 올바르지 않습니다',
  // 「이미 접수됐다」 패널의 제목은 **이 표에 없다** → 아래 `EUM_DONE_STATE`.
  //
  // 고친 결함: 그 제목은 한동안 여기 `used: '이미 신청하셨습니다'` 로 있었고, 같은 패널의
  // 본문은 「**이미 신청이 접수되었습니다**. 담당자가 곧 전화로 안내해 드립니다」였다 —
  // 바로 위 두 줄이 없앤 그 중복이 한 자리 더 있었던 셈이다. 그때 이 자리를 남긴 이유는
  // 「본문은 완료 화면과 **같은 문장**이어야 한다」는 13회차의 계약이 먼저였기 때문인데,
  // 그 계약을 깨지 않는 길은 이미 이 파일에 쓰여 있었다(제목·본문을 **한 토막에서 나눠
  // 쓴다**). 그래서 제목을 접수 사실의 표로 옮겼다 — 이 표는 「무엇이 **잘못**됐는가」를
  // 말하는 자리이고, 그 패널의 제목은 「무엇이 **이미 되어 있는가**」다.
};

// 어르신이 스스로 할 수 있는 일은 하나뿐이다(재발급 수단이 없다). 패널 본문은 이 한 줄이고,
// 아래 EUM_TOKEN_MESSAGE 의 뒤 문장도 같은 토막이다 — 두 벌이 되지 않게 한 자리에만 적는다.
export const EUM_PANEL_ASK = '담당자에게 다시 요청해 주세요';

// 토큰 검증 실패 사유별 안내문(사유 이름은 lib/eumToken.verifyEumToken 의 `reason` 과 같다).
//
// 왜 만료만 다른 문장인가: 만료는 **담당자가 새 링크를 보내면 해결되는 상태**이고, 나머지는
// 링크 자체가 잘못된 상태다. 어르신이 다음에 할 일이 같아 보여도(담당자에게 연락) 무엇이
// 잘못됐는지는 다르게 말해야 한다 — 「만료」라고 들은 어르신은 늦었구나 알고, 「올바르지
// 않다」고 들은 어르신은 링크가 잘려 왔는지 다시 본다.
//
// 이 표가 쓰이는 자리는 **제목이 없는 알림 한 줄**이다(제출이 401·410 으로 돌아왔을 때의
// Alert). 그래서 혼자서도 뜻이 서게 두 토막을 이어 둔다 — 제목이 있는 패널은 같은 토막을
// 제목과 본문으로 **나눠** 쓴다(위 EUM_PANEL_TITLE·EUM_PANEL_ASK).
//
// 문장 끝에 마침표를 두지 않는다. 같은 알림 자리의 다른 문장들도 마침표가 없다 —
// 섞이면 화면마다 끝이 달라진다.
export const EUM_TOKEN_MESSAGE = {
  expired: `${EUM_PANEL_TITLE.expired}. ${EUM_PANEL_ASK}`,
  signature: `${EUM_PANEL_TITLE.link}. ${EUM_PANEL_ASK}`,
  malformed: `${EUM_PANEL_TITLE.link}. ${EUM_PANEL_ASK}`,
  missing: `${EUM_PANEL_TITLE.link}. ${EUM_PANEL_ASK}`,
  // 수명이 상한 밖인 토큰(`lib/eumToken.withinTokenLifetime`). 어르신에게는 「잘못된 링크」와
  // **같은 사실**이다 — 어느 쪽이든 그 링크로는 신청할 수 없고 할 일은 담당자에게 청하는
  // 것뿐이며, 그 차이를 어르신이 가릴 길도 없다(만료와는 다르다: 만료는 늦은 것이고 이쪽은
  // 우리가 발급하지 않은 모양이다). 사유를 따로 둔 이유는 **서버 로그**다 —
  // 라우트가 `token_lifetime` 으로 남기므로 「상한을 넘는 링크가 제시됐다」를 되짚을 수 있다
  // (모르는 사유로 떨어뜨리면 그 사실이 malformed 에 섞여 사라진다).
  lifetime: `${EUM_PANEL_TITLE.link}. ${EUM_PANEL_ASK}`,
};

// 모르는 사유는 **가장 보수적인 안내**(잘못된 링크)로 떨어진다 — 빈 문자열을 돌려주면
// 화면이 아무 말도 하지 않는 상태가 되고, 그것이 이 함수가 막아야 하는 결과다.
// 등록부에 **실제로 적힌 문장**일 때만 쓴다: `EUM_TOKEN_MESSAGE[reason]` 을 그대로 믿으면
// 'constructor'·'__proto__' 같은 이름이 프로토타입의 값을 끌어와 참처럼 보이고,
// 그것이 그대로 화면에 그려진다(어르신이 읽을 수 없는 글자가 안내문 자리에 앉는다).
export function tokenMessage(reason) {
  const msg = EUM_TOKEN_MESSAGE[reason];
  return typeof msg === 'string' ? msg : EUM_TOKEN_MESSAGE.malformed;
}

// 사유 → 패널 제목의 **자리 이름**. 사유 이름은 위 표와 같은 것(verifyEumToken 의 reason)이라
// 두 함수가 같은 사유를 다르게 가를 수 없다 — 그 어긋남은 테스트가 양방향으로 막는다
// (모든 사유에서 `tokenMessage(reason)` 가 `panelTitle(reason)` 로 시작해야 한다).
const PANEL_TITLE_SLOT = {
  expired: 'expired',
  signature: 'link',
  malformed: 'link',
  missing: 'link',
  lifetime: 'link',
};

// 사유별 패널 제목. 모르는 사유는 tokenMessage 와 같은 쪽(잘못된 링크)으로 떨어진다 —
// 빈 제목을 돌려주면 되돌릴 단추가 없는 화면의 머리글이 사라진다.
export function panelTitle(reason) {
  const slot = typeof PANEL_TITLE_SLOT[reason] === 'string' ? PANEL_TITLE_SLOT[reason] : 'link';
  return EUM_PANEL_TITLE[slot];
}

// ── 제출이 되지 않았을 때의 안내(알림 자리) ────────────────────────────────
//
// 고친 결함: 이 다섯 문장은 `SeniorFlow` 안에 **손으로 적혀** 있었고, 그래서 두 가지가
// 아무 신호 없이 들어와 있었다.
//
//   (1) **자리를 가리키는 말.** 둘이 「**아래** 단추를 한 번 더 눌러 주세요」였다. 그런데 그
//       안내는 주버튼보다 **위**에 그려졌으므로, 안내가 생기는 순간 가리키던 단추를 자기가
//       아래로 밀어냈다 — 어르신이 외워 둔 자리에 더는 단추가 없다. 그리고 「아래」는
//       **눈에만 뜻이 있는 말**이다(스크린리더에 위·아래는 없고, 그 순간 포커스는 이미 그
//       단추에 남아 있다 — 8회차의 `aria-disabled`). 나머지 셋은 처음부터 자리를 가리키지
//       않았다(「연결을 확인하고 다시 눌러 주세요」·「잠시 후 다시 눌러 주세요」) — 같은
//       자리의 다섯 문장이 두 규칙으로 갈려 있었던 셈이다.
//   (2) **문장 끝.** 위 `EUM_TOKEN_MESSAGE` 는 마침표로 끝내지 않는다. 그런데 같은 알림
//       자리에 그려지는 이 문장들은 전부 마침표로 끝났고, 그 자리에는 401 안내
//       (`tokenMessage('signature')`)도 함께 온다 — 어르신이 어느 실패를 만나느냐에 따라
//       문장의 끝이 달랐다. 9회차가 없앤 「마침표가 하나 더 붙은 두 번째 판본」이 **같은
//       자리에 네 벌** 남아 있었다.
//
// 그래서 문장을 표로 모으고 규약을 테스트가 들게 한다(tests/eummessage.test.mjs) —
// 자리를 가리키는 낱말이 없고, 끝은 위 표와 같은 한 가지다. 자리를 가리키지 않아도 뜻이
// 서는 이유는 안내가 **주버튼 바로 아래**에 붙고(ui.jsx 의 Alert · 더는 단추를 밀어내지
// 않는다) 키보드·스크린리더에서는 포커스가 그 단추에 남아 있기 때문이다.
export const EUM_SUBMIT_MESSAGE = {
  // 고른 것이 사라진 채 제출에 닿았다 — 되돌릴 길은 처음부터 다시 고르는 것뿐이다.
  // 이 안내만 **고르는 화면(1단계)** 에 그려진다(나머지는 확인 화면).
  selection: '선택이 저장되지 않았습니다. 처음부터 다시 골라 주세요',
  // 브라우저가 오프라인이라고 말한 경우 — 눌러도 네트워크를 두드리지 않는다.
  offline: '인터넷 연결이 끊겼습니다. 연결을 확인하고 다시 눌러 주세요',
  // 응답이 오지 않았거나 상한(8초)을 넘겨 우리가 끊은 경우. 다시 눌러도 안전하다 —
  // 첫 요청이 서버에 닿았다면 409 로 돌아와 **완료 화면**이 된다.
  unreachable: '연결이 원활하지 않습니다. 한 번 더 눌러 주세요',
  // 한도에 걸린 경우(429). 지금 할 수 있는 일은 잠시 기다리는 것뿐이다.
  tooMany: '잠시 후 다시 눌러 주세요',
  // 그 밖에 서버가 받아 주지 않은 경우 — 무엇이 잘못됐는지 모를 때의 가장 보수적인 안내다.
  rejected: '신청을 접수하지 못했습니다. 한 번 더 눌러 주세요',
};

// 모르는 사유는 `rejected`(접수되지 않았다는 사실만 말한다)로 떨어진다. 빈 문자열을
// 돌려주면 실패한 제출이 **아무 말도 없이** 끝나고, 그것이 이 함수가 막아야 하는 결과다.
// 프로토타입 이름을 걸러 내는 이유는 위 tokenMessage 와 같다.
export function submitMessage(reason) {
  const msg = EUM_SUBMIT_MESSAGE[reason];
  return typeof msg === 'string' ? msg : EUM_SUBMIT_MESSAGE.rejected;
}

// ── 접수가 끝났다는 사실 ───────────────────────────────────────────────────
//
// 고친 결함: 「이미 접수됐다」는 사실을 보여 주는 화면은 둘이다 — 링크를 **다시 열었을 때**
// (진입 안내 · `[token]/page.jsx`)와 제출이 **409 로 돌아왔을 때**(완료 화면 · `SeniorFlow`).
// 9회차에 그 둘을 「단일 출처」로 묶었다고 적었고 테스트 이름도 「진입 안내와 완료 화면의
// 문구는 단일 출처다」였지만, 그 테스트가 실제로 대조한 것은 **뒤에 붙는 두 힌트**뿐이었다.
// 정작 두 화면의 **본문**은 각자 적혀 있었고, 그래서 서로 다른 말을 했다.
//   · 완료 화면 → 「이미 접수된 신청이 있습니다. 담당자가 곧 전화로 안내해 드립니다.」
//     (할 일이 없다는 뜻 — 맞는 말이다)
//   · 진입 안내 → 「이미 신청이 접수된 링크입니다. **담당자에게 문의해 주세요**」
//     (할 일이 있다는 뜻 — 틀린 말이다)
// 틀린 쪽의 대가가 이 과제가 줄곧 막아 온 것이다. 그 화면은 바로 아래에서 「바꾸고 싶으시면
// 담당자에게 말씀해 주세요」(조건부)와 「이제 이 화면을 닫으셔도 됩니다」(할 일 없음)를
// 이어서 말한다 — 한 화면이 **세 가지 다른 말**을 하고, 그중 맨 위의 것만 무조건 전화를
// 걸라고 한다. 신청이 멀쩡히 접수된 어르신이 담당자에게 전화하면 담당자는 **새 링크**를
// 보내고, 새 링크는 소진 키가 달라 재신청이 실제로 통한다 → 명단에 두 건. 9회차가 힌트
// 한 줄로 막은 그 중복을, **같은 화면의 본문**이 그대로 만들고 있었다.
//
// 그래서 사실을 말하는 문장도 한 벌로 묶는다. `lib/eumConsume.EUM_CONSUME_MESSAGE.used` 가
// 이 표를 가리키므로 진입 안내·409 응답·완료 화면이 전부 같은 문장을 쓴다.
//
// ── 그 한 벌을 **두 토막**으로 나눈다(제목이 있는 자리를 위해) ──────────────
//
// 고친 결함: 「이미 접수됐다」를 보여 주는 두 화면 중 **진입 패널**은 제목이 있는 자리인데,
// 그 제목(`EUM_PANEL_TITLE.used` — 「이미 신청하셨습니다」)과 본문의 첫 문장(「이미 신청이
// 접수되었습니다」)이 **같은 사실을 두 번** 말했다. 그 패널은 전환과 함께 제목으로 포커스를
// 옮기므로(11회차) 듣는 어르신은 제목을 듣고 이어지는 본문에서 방금 들은 말을 한 번 더 듣고,
// 보는 어르신에게는 24px 넘는 글자 두 줄이 같은 말을 한다 — 9회차가 만료·잘린 링크 패널에서
// 없앤 중복과 **같은 것**이다. 되돌릴 단추가 없는 화면에서 읽을 것 둘 중 하나가 쓸모없었다.
//
// 그때 이 자리를 남긴 이유는 「본문은 완료 화면과 **같은 문장**이어야 한다」는 13회차의
// 계약이 먼저였기 때문이다. 그 계약을 깨지 않는 길은 이미 이 파일에 **두 번** 쓰여 있었다 —
// `EUM_PANEL_TITLE`/`EUM_PANEL_ASK`(제목 없는 알림 한 줄은 이어 쓰고, 패널은 나눠 쓴다)와
// `EUM_SOON_LEAD`/`EUM_SOON_NEXT`(앞 토막은 한 벌, 뒤 토막만 자리별)다. 즉 **고칠 수 없는
// 자리가 아니라 이미 두 번 쓴 수단을 세 번째로 쓰면 되는 자리**였다.
//
// 그래서 토막을 둘로 나누고, 이어 쓴 문장은 **여기서 조립한다** — 글자는 한 자도 바뀌지
// 않으므로 409 응답과 완료 화면의 문장은 종전과 같다. 두 토막이 한 자리에서 나오므로 진입
// 패널의 「제목 + 본문」과 그 이어 쓴 문장은 **갈라질 수 없다**(13회차의 계약은 그대로다).
//
// 자리별 규칙(위 두 표와 같다)
//   · 제목이 있는 패널(진입 「이미 접수됐다」) → 제목 `EUM_DONE_STATE.already` · 본문 `EUM_DONE_NEXT`
//   · 제목이 없거나 제목이 **다른 사실**을 말하는 자리(409 응답 본문 · 완료 화면 — 그 제목은
//     단계 제목이다) → 이어 쓴 `EUM_DONE_MESSAGE`

