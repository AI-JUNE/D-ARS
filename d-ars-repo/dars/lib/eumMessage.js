// 테스트가 양쪽에서 대조한다**(「닫힙니다」가 되살아나면 실패한다).
// 초 숫자는 여기 넣지 않는다: 이 문장은 한 번만 낭독돼야 하고, 매초 바뀌는 숫자를 섞으면
// 1초마다 말을 끊고 처음부터 다시 읽는다(초 숫자는 화면이 aria-hidden 으로 따로 붙인다).
export const EUM_SOON_LEAD = '잠시 후 링크가 만료됩니다';

export const EUM_SOON_NEXT = {
  // 1단계 — 아직 아무것도 고르지 않았다. 남은 일이 둘이라는 것까지 말해 준다.
  1: '활동과 시간을 고르고 신청해 주세요',
  // 2단계 — 활동은 골랐다. 남은 것은 시간 하나다.
  2: '시간을 고르고 신청해 주세요',
  // 3단계 — 신청 단추가 화면에 있는 **유일한** 단계다. 그래서 여기서만 그 단추를 가리킬 수
  // 있고, 가리키는 방법은 **이름**이다(위 EUM_ACTION 주석 — 「아래」는 눈에만 뜻이 있다).
  // 예전 문장은 「지금 고르신 것을 신청해 주세요」였는데, 고른 것은 바로 위 요약이 이미 말하고
  // 있고(그 요약은 주버튼의 설명으로도 연결돼 있다 · ui.jsx 의 EUM_SUMMARY_ID) 이 문장이 더
  // 보태야 하는 한 마디는 **무엇을 누르는가**였다 — 경고는 화면 맨 위, 단추는 맨 아래다.
  3: `${EUM_ACTION.submit} 단추를 눌러 주세요`,
};

// ── 제출이 떠 있는 동안에는 **그 단추가 그 이름으로 화면에 없다** ────────────
//
// 고친 결함: 위 3단계 토막은 눌러야 하는 단추를 **이름**으로 가리킨다(25회차). 그런데 그
// 단추의 글자는 상태에 따라 바뀐다 — 제출이 떠 있는 동안 그 자리에 적힌 것은
// `EUM_ACTION.submitting`(「신청하는 중…」)이고 「이대로 신청하기」는 화면에 **없다**.
// 그래서 하필 가장 급한 순간에 경고가 **없는 이름으로** 단추를 가리켰다: 남은 시간이
// 1분을 막 넘긴 상태에서 누른 제출은 응답을 기다리는 사이(상한 8초) 눈금이 1분 아래로
// 내려가므로, 경고가 **처음 뜨는 시점이 제출 중**인 경우가 드물지 않다. 그때 어르신이
// 듣는 말은 「이대로 신청하기 단추를 눌러 주세요」인데 찾을 수 있는 단추는 「신청하는 중…」
// 하나이고, 그것을 눌러도 아무 일도 일어나지 않는다(중복 전송을 우리가 막는다 ·
// SeniorFlow 의 submittingRef) — 14회차가 「눌러도 꼼짝하지 않는 단추」를 가장 나쁜 결과로
// 꼽은 바로 그 모양이다.
// 바로 위 등록부의 가드가 그 사실을 이미 말하고 있었다: 1·2단계가 이 이름을 쓰지 못하는
// 사유가 「그 단추가 화면에 없다」였는데, 같은 사유가 **제출 중의 3단계**에도 그대로
// 적용되는 것을 아무도 보지 않았다(15·16·18·22~25회차의 「가드·문구가 자기 사유보다
// 좁았다」의 다음 자리이고, 이번에 좁았던 축은 **단계가 아니라 상태**다).
//
// 그래서 제출이 떠 있는 동안의 「할 일」을 따로 둔다. 이 화면은 이미 같은 결정을 한 번
// 했다 — **응답을 기다리는 동안 화면은 스스로 만료를 선언하지 않는다**(22회차의 `!busy`:
// 만료의 최종 판정자는 서버다). 그 결정의 짝은 「기다리는 동안 어르신에게 할 일을 주지
// 않는다」이고, 경고만 그 밖에 있었다. 앞 토막(「잠시 후 링크가 만료됩니다」)은 그대로
// 둔다 — 어느 상태에서나 참이고, 들리지 않는 것이 이 경고에서 가장 비싼 결과다(15회차).
// (정정: 「어느 상태에서나 참」이 한 상태에서 참이 아니었다 — 눈금이 **바닥에 닿은 뒤**다.
//  그 상태가 보이는 경로는 하필 이 문단이 말하는 **제출 중**이다: 응답을 기다리는 사이 0 에
//  닿으면 「잠시 후」가 이미 지난 일을 가리킨다. 지금은 바닥에서 앞 토막을 떼고 뒤 토막만
//  말한다 · 아래 soonMessage 의 `atFloor` 주석 · 29회차.)
// 등록부에 넣지 않고 따로 두는 이유: 그 표는 **단계 ↔ 이름**을 양방향으로 대조하는
// 자리라(경고가 그려지는 단계는 1~3), 단계가 아닌 이름이 끼면 그 대조가 무의미해진다.
export const EUM_SOON_BUSY = '신청을 보내는 중이니 기다려 주세요';

// 지금 단계에서 할 일을 붙인 경고 한 문장.
//
// `busy` 는 제출이 떠 있는가다 — 참이면 단계를 보지 않는다(위 주석). 제출 단추는 3단계에만
// 있으므로 실제로 갈리는 자리는 그 한 단계뿐이지만, 판정의 기준은 「그 말이 가리키는 것이
// 지금 화면에 있는가」이지 단계가 아니다.
//
// 모르는 단계는 **앞 토막만** 돌려준다(빈 문자열이 아니다). 여기서 침묵을 고르지 않는 이유:
// 앞 토막은 어느 단계에서나 참이고(링크가 곧 만료된다), 그것을 듣지 못하는 것이 이 경고에서
// 가장 비싼 결과다 — 보이지 않는 어르신은 남은 1분을 **모르는 채** 고르다가 화면이 만료
// 패널로 뒤집히는 것을 맞는다(15회차가 영역을 미리 두어 겨우 들리게 만든 그 문장이다).
// 기본값을 두지 않는 EUM_NOTICE_FOOT·EUM_PRIOR_TAIL 과 방향이 다른 것은, 그 둘은 **틀린
// 말이 조용히 붙는 것**이 위험이었고 여기는 **참인 말이 조용히 사라지는 것**이 위험이기
// 때문이다. 어느 쪽이든 지어내지 않는다는 선은 같다.
// 프로토타입 이름을 걸러 내는 이유는 위 tokenMessage 와 같다.
//
// ── `atFloor`: 앞 토막이 **그 시점에만** 참이 아니다 ──────────────────────────
//
// 고친 결함: 바로 위 두 문단이 「앞 토막은 어느 상태에서나 참이다」라고 두 번 적어 두었는데,
// 참이 아닌 상태가 하나 있었다 — 눈금이 **바닥(0)에 닿은 뒤**다. 그때 「잠시 후」는 앞을
// 가리키는 말인데 그 일은 이미 일어났다(단조 눈금이면 서버 기준으로도 만료다).
// 그 상태가 화면에 보이는 경로는 둘이고 둘 다 패널이 오지 않는 자리다
// (제출 중 · 기기 시계 폴백 · lib/eumCountdown 의 warnPhase 주석).
// 그래서 바닥에서는 **앞 토막을 떼고 뒤 토막만** 말한다 — 뒤 토막은 「이 화면에서 할 일」
// 이라 바닥에서도 그대로 참이다(제출 중이면 기다리는 것, 고르는 중이면 고르고 신청하는 것 ·
// 판정은 서버가 하고, 410 이면 그 사유를 패널이 안내한다).
// **새 문장을 지어내지 않는다**: 모르는 것(언제 만료되는가)은 말하지 않고, 아는 것(할 일)만
// 남긴다 — 24회차가 만료 안내에서 「5분」을 지운 것과 같은 꼴이다.
export function soonMessage(step, busy = false, atFloor = false) {
  const tail = busy ? EUM_SOON_BUSY : EUM_SOON_NEXT[step];
  const next = typeof tail === 'string' && tail ? tail : '';
  // 바닥에서 할 말까지 모르면 **아무 말도 하지 않는다** — 남는 것이 앞 토막뿐이고 그것이
  // 바로 참이 아닌 토막이다(틀린 말을 조용히 붙이지 않는다 · EUM_NOTICE_FOOT 과 같은 선).
  if (atFloor) return next ? `${next}.` : '';
  return next ? `${EUM_SOON_LEAD}. ${next}.` : `${EUM_SOON_LEAD}.`;
}

// ── 그 경고 옆의 **눈금 숫자를 읽는 한 줄**도 문구다 ────────────────────────
//
// 고친 결함: 초 표시를 화면이 **손으로 적고** 있었다 —
// `<span aria-hidden="true"> 남은 시간 {secondsLeft(left)}초</span>`(SeniorFlow). 29회차가
// 단계 표시에서, 25회차가 조작 요소 이름에서 고친 것과 **같은 모양**이고, 이 화면군에서
// 화면이 직접 지어 그리던 **마지막 문구**였다.
// 왜 아무도 몰랐나: 이 문장은 가운데에 **값이 끼어 있다**. 그래서
//   · 「화면이 손으로 적는 문구」 대조는 한글이 든 리터럴과 JSX 글자 노드를 긁는데, 그 글자
//     노드 정규식이 `{`·`}` 를 아예 받지 않아 **이 문단을 한 번도 지나가지 않았다**
//     (tests/eumseniorui.test.mjs — 가드가 자기 이름보다 좁았던 또 한 자리다. 값이 끼인
//     글자 노드는 전부 같은 길로 빠져나간다).
//   · 「코드가 보장하지 않는 수명을 문구가 말하지 않는다」 대조도 **리터럴 숫자**만 찾으므로
//     여기 걸리지 않는다(그 테스트의 주석이 이 문단을 예로 들어 적어 두기까지 했다 —
//     사실은 맞았지만 그것은 「숫자는 괜찮다」는 뜻이고 **문장이 등록부 밖이라는 사실**은
//     아무도 보지 않았다).
// 즉 어르신이 읽는 글자 한 줄이 두 가드의 틈에 정확히 들어가 있었다.
//
// 수는 여기서 짓지 않는다 — 세는 쪽은 `lib/eumCountdown.secondsLeft` 하나이고(올림이라
// 「0초」가 남은 채로 머무르지 않는다) 이 함수는 그 수를 **문장에 끼운다**. 모르는 값은
// ''(화면은 그때 아무 글자도 그리지 않는다 — 지어내지 않는다).
//
// 낭독은 **하지 않는다**(화면이 `aria-hidden` 으로 가린다 · 27~29회차 그대로): 매초 바뀌는
// 숫자를 살아 있는 낭독 영역에 들이면 1초마다 말이 끊기고 문장이 처음부터 다시 읽힌다.
// 그래서 이 한 줄은 **보이는 쪽에만** 전해진다 — 그 자리의 남은 결정은 EUM_INTEGRATION.md
// 의 「다음에 볼 자리」에 그대로 둔다(거친 눈금을 영역 안으로 들이는 일은 375px 실렌더 없이
// 고를 수 없다). 바닥(0)에서는 화면이 이 줄을 아예 그리지 않는다(29회차).
export function secondsMessage(seconds) {
  const n = typeof seconds === 'number' && Number.isFinite(seconds) ? Math.floor(seconds) : NaN;
  if (!Number.isFinite(n) || n < 0) return '';
  return `남은 시간 ${n}초`;
}
