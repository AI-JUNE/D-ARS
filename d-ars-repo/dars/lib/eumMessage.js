//
// 고친 결함: 이 경고는 문장 **한 벌**이었고(`lib/eumCountdown.EUM_SOON_MESSAGE`), 신청 흐름
// 1~3단계 어디서나 같은 말을 했다 — 「잠시 후 링크가 만료됩니다. **지금 고르신 것을 신청해
