// 「아는 사실」과 「전에 낸 내용」 사이를 가르는 자리. 예전에는 줄표(' — ')였는데 그것도
// 낭독되지 않아(EUM_MUTE_MARKS) 세 토막이 한 문장으로 들러붙었다 — "내용이 있습니다 산책
// 나들이 오전 9시 12시 그대로 괜찮으시면". 마침표는 어떤 리더든 **문장 끝**으로 읽는다.
export const EUM_PRIOR_JOIN = '. ';

// 화면에 띄울 한 문장. 보여 줄 것이 없거나 자리 이름을 모르면 ''(화면은 아무것도 그리지 않는다).
// 조사(「…으로」) 문제를 피해 요약을 문장 중간에 그대로 끼운다 — 시간대 이름이 '지' 나 '요' 로
// 끝나므로 조사를 붙이면 어느 쪽이든 틀린 말이 된다.
export function priorLocalNotice(prior, where) {
  // 등록부에 **실제로 적힌 문장**일 때만 쓴다. `EUM_PRIOR_TAIL[where]` 를 그대로 믿으면
  // 'constructor'·'__proto__' 같은 이름이 프로토타입의 값을 끌어와 참처럼 보인다.
  const tail = typeof EUM_PRIOR_TAIL[where] === 'string' ? EUM_PRIOR_TAIL[where] : '';
  const s = summaryText(prior ? { activity: prior.activity, timeslot: prior.timeslot } : null);
  if (!s || !tail) return '';
  return `이 기기에서 전에 신청하신 내용이 있습니다${EUM_PRIOR_JOIN}${s}. ${tail}`;
}

// ── 되살아난 화면이 「방금 다시 시도를 눌렀다」를 안다 ──────────────────────
//
// 고친 결함: 오류 경계(app/eum/error.jsx)의 「다시 시도」는 누르는 순간 **자기 자신이 사라지는**
// 단추다 — `reset()` 이 그 화면을 걷어내고 신청 흐름을 되살린다. 그러면 포커스가 얹혀 있던 그
// 단추가 문서에서 사라지므로 브라우저는 포커스를 body 로 돌려보낸다. 11·12·13회차가 세 번 고친
// 바로 그 모양인데(흐름 → 만료 패널 · 흐름 → 오류 경계 · 새로 태어난 낭독 영역), **경계에서
// 나오는 길**만 손대지 않은 채 남아 있었다. 되살아난 흐름은 첫 렌더에서 포커스를 옮기지
// 않는데(SeniorFlow), 그 규칙의 근거가 "사용자가 아직 아무 조작도 하지 않았다" 인데 이 경우엔
// **조작해서 온 것**이다. 그래서 어르신은 눌렀는데 들리는 말이 한 마디도 없고, 다음 Tab 은
// 문서 맨 앞에서 시작한다 — 그 화면은 이 흐름의 유일한 되돌리기 수단이었다.
//
// 두 화면은 서로를 모른다(경계는 무엇이 되살아날지 알 수 없고, 흐름은 자기가 왜 다시 그려졌는지
// 알 수 없다). 그래서 사실 하나를 **문서에** 적어 넘긴다.
//   · 모듈 변수로 넘기지 않는다 — 두 화면은 서로 다른 번들 엔트리에 실릴 수 있고, 같은 파일이
//     두 번 평가되면 변수도 두 벌이 된다(12회차에 소진 스토어가 바로 그 길로 갈라졌다).
//   · 저장소(localStorage·sessionStorage)에 넣지 않는다 — 그것들은 문서를 넘겨 살아남으므로,
//     다음에 링크를 여는 어르신이 **누른 적 없는 누름**의 뒤처리를 받는다.
//   문서 뿌리의 속성은 이 문서 안에서만 살고(새로 열면 없다) 번들 경계와 무관하다.
// 판정은 여기 두고(순수 · 단위 테스트) 화면은 `document.documentElement` 만 넘긴다 —
// 이 모듈은 DOM 을 import 하지 않는다(서버 라우트도 같은 파일을 쓴다).
//
// ── 그 깃발이 말하는 사실은 **하나인데 쓸 자리는 둘이었다** ──────────────────
// 이 깃발이 적어 넘기는 사실은 「이 마운트는 **누름의 결과**다」다. 한동안 그것을 읽어
// 포커스만 옮겼는데, 같은 사실이 필요한 자리가 하나 더 있었다 — **떨리는 손의 두 번째 탭**
// (아래 tapSettled)이다. 「다시 시도」는 자기 자신이 사라지는 단추이므로 그 두 번째 탭은
// 되살아난 흐름에 떨어지고, 되살아나는 단계는 주소가 정한다(restorePoint) — ?step=3 이면
// 그 자리에 「이대로 신청하기」가 오고, 그것은 오류 화면의 「다시 시도」와 **같은 주버튼**
// (같은 style · 같은 최소 높이)이다. 즉 되돌리려고 누른 손이 **읽지 않은 신청**을 접수시킬
// 수 있었다. 20회차가 눈금을 마운트에 적지 않기로 한 근거("겨눈 손이 없다")가 하필 **겨눈
// 손이 있는 이 마운트**까지 덮고 있었던 셈이다. 지금은 흐름이 이 깃발을 **한 번 읽어 두
// 가지**에 쓴다(SeniorFlow 의 첫 효과) — 사실을 두 번 적지 않는다.
export const EUM_RETRY_FLAG = 'data-eum-retried';

// 적는다. 적지 못해도 **던지지 않는다** — 이 한 줄이 「다시 시도」를 죽이면 안 된다
// (잃는 것은 포커스 이동 하나이고, 얻는 것이 신청 자체다).
export function markRetried(root) {
  try {
    if (!root || typeof root.setAttribute !== 'function') return false;
    root.setAttribute(EUM_RETRY_FLAG, '1');
    return true;
  } catch {
    return false;
  }
}

// 읽고 **지운다** — 한 번만 쓰이는 사실이다. 지우지 않으면 같은 문서에서 흐름이 다시
// 그려질 때마다 누른 적 없는 누름을 근거로 포커스를 빼앗는다.
export function takeRetried(root) {
  try {
    if (!root || typeof root.getAttribute !== 'function') return false;
    if (root.getAttribute(EUM_RETRY_FLAG) === null) return false;
    if (typeof root.removeAttribute === 'function') root.removeAttribute(EUM_RETRY_FLAG);
    return true;
  } catch {
    return false;
  }
}

// ── 화면이 바뀐 직후의 두 번째 누름은 **다음 화면의 다른 뜻**이 된다 ──────────
//
// 고친 결함: 이 과제는 「손이 떨려 두 번 누르는 것은 이 사용자층에서 흔하다」를 두 번 근거로
// 삼아 고쳤다 — 제출(8회차의 `submittingRef`)과 되돌아가기(14회차의 `backFromRef`)다.
// 그런데 **앞으로 나아가는 쪽**(선택지 버튼)에는 그 가드가 없었고, 하필 거기서 두 번째 누름이
// 가장 비싸다: 눌린 순간 화면이 **다음 단계로 바뀌고**, 그 자리에는 다른 뜻의 단추가 온다.
//   · 1단계 선택지 네 개와 2단계 선택지 네 개는 **같은 자리·같은 모양**이다(같은 style·같은
//     최소 높이). 활동을 고른 손가락이 한 번 더 떨어지면 그 아래에 있는 것은 **시간대**다 —
//     어르신은 읽지도 않은 시간대를 고른 채 확인 화면을 보게 되고, 화면은 그것을 「이대로
//     신청할까요?」라고 묻는다. 무엇이 잘못됐는지 알 단서가 화면에 없다(고른 것 ✓ 는
//     어르신이 **지나친 화면**에 있었다).
//   · 2→3 은 더 나쁘다. 확인 화면의 **주버튼**이 선택지가 있던 자리 근처에 오므로, 두 번째
//     누름이 「이대로 신청하기」에 떨어질 수 있다 — 그러면 확인 화면을 **한 번도 읽지 않은
//     신청**이 접수되고, 링크는 1회용이라 되돌릴 길이 없다(바꾸려면 담당자에게 전화해야 하고,
//     그 전화가 새 링크를 부르고, 새 링크는 명단에 두 건을 남긴다).
// 두 번째 탭이 click 으로 도착하면(브라우저·제스처 설정에 따라 확대로 흡수되는 경우도 있지만
// 그쪽은 애초에 해가 없다) 그것은 **그 순간 손가락 아래 있는 요소**로 간다. 즉 우리에게는
// "두 번 눌렸다" 가 아니라 **"다른 화면이 한 번 눌렸다"** 로 도착하므로, 같은 요소를 지키는
// `submittingRef`·`backFromRef` 식 가드로는 잡히지 않는다.
//
// 그래서 **화면이 방금 바뀌었는가**를 본다. 단계를 옮기는 자리(`go`)가 그 순간의 눈금을
// 적어 두고, 조작 요소는 그 뒤 잠깐 동안의 누름을 삼킨다.
//
// (정정 · 적는 자리는 하나가 아니었다) 처음에는 눈금을 적는 자리를 `go` **하나**로 두고
// "마운트·popstate 에는 겨눈 손이 없으므로 적지 않는다" 고 적었다. 그 근거는 맞지만 한
// 마운트에는 맞지 않는다 — **오류 화면의 「다시 시도」로 되살아난 마운트**다. 그 단추는
// 눌린 순간 자기 자신이 사라지고(reset), 되살아나는 단계는 주소가 정하므로(restorePoint)
// 두 번째 탭이 떨어지는 자리에 **같은 모양의 주버튼**(「이대로 신청하기」)이 올 수 있다.
// 가름선은 「마운트인가」가 아니라 「그 전환이 **누름의 결과**인가」이고, 그 사실은 이미
// 문서에 적혀 있었다(위 EUM_RETRY_FLAG — 그때까지는 포커스에만 쓰였다).
//   · 400ms 은 "사람이 새 화면을 읽고 고를 수는 없는 시간" 으로 잡은 운영 기준값이며 실측
//     지표가 아니다(떨림이 만드는 두 번째 탭은 보통 그 안에 떨어진다).
//   · (정정) 이 자리는 「눈금은 **단조 눈금**(lib/eumCountdown.nowTick)이다 — 기기 시계를
//     고쳐도 뒤로 가지 않는다」고 단언했다. 그것은 `performance.now()` 가 있는 환경에서만
//     참이고, 없으면 `nowTick` 은 **기기 시계**로 물러선다(그 파일의 EUM_TICK_WALL 주석).
//     즉 서술이 코드보다 앞서 있던 또 한 자리다. 다만 **고칠 것은 없다** — 이 판정의 두
//     방향이 이미 그 환경을 덮고 있다:
//       · 시계가 **뒤로** 뛰면 경과가 음수라 아래 분기가 통과시킨다(「모를 때는 통과」).
//       · 시계가 **앞으로** 뛰면 경과가 과장돼 400ms 가 지난 것처럼 보이고, 역시 통과한다.
//     둘 다 통과이고, 통과는 이 판정이 **일부러 고른 실패 방향**이다(바로 아래 두 줄 —
//     판정 실패가 어르신의 누름을 막아서는 안 된다). 그래서 여기서는 출처를 가리지 않는다.
//     출처를 가려야 하는 자리는 **되돌릴 수 없는 선언**이고, 그것은 저쪽에 하나뿐이다
//     (lib/eumCountdown.selfExpired — 화면이 스스로 띄우는 만료 패널).
//     남는 범위: 그 환경에서 시계가 하필 400ms 창 안에 앞으로 뛰면 삼켜야 할 탭 하나가
//     통과한다. 그 동시 발생을 막는 길은 없고(400ms 는 시계 보정 주기보다 훨씬 짧다),
//     막으려고 「모를 때 삼키는」 쪽으로 돌리면 유일한 진행 수단이 먹통이 된다.
//   · 삼키는 쪽의 최악은 **한 번 더 눌러야 하는 것**이고(400ms 뒤면 통한다), 삼키지 않는
//     쪽의 최악은 **읽지 않은 선택이 접수되는 것**이다. 그래서 삼키는 쪽을 고른다.
//   · 반대로 **모를 때는 통과시킨다**(아래). 여기서 닫는 것은 어르신의 누름이고, 판정 실패가
//     유일한 진행 수단을 먹통으로 만드는 것은 14회차가 「모를 때는 가로채지 않는다」로 고른
//     쪽과 정반대다. 모르는 것이 누름을 막아서는 안 된다.
//
// 어디에 거는가 — **삼킨 대가가 보이지 않거나 되돌릴 수 없는 자리**에만 건다:
//   · 선택지(활동·시간대) — 잘못 들어간 선택은 어르신이 **지나친 화면**에 있어 보이지 않는다.
//   · 「이대로 신청하기」 — 접수는 1회용 링크에서 되돌릴 수 없다.
// 되돌아가기(「앞 화면으로」·「다시 고르기」)에는 **걸지 않는다.** 거기 잘못 떨어진 탭의
// 결과는 **앞 화면으로 돌아간 것**이고, 그것은 눈에 보이며 한 번 더 눌러 되돌릴 수 있다 —
// 반대로 삼켰을 때 잃는 것은 이 화면의 유일한 되돌리기 수단이다(14회차가 「눌러도 꼼짝하지
// 않는 단추」를 가장 나쁜 결과로 꼽은 그 자리다). 같은 자리의 두 번째 누름은 이미
// `backFromRef`(14회차)가 삼킨다.
export const EUM_SETTLE_MS = 400;

// 지금 누름을 받아도 되는가. `movedTick` 은 마지막 단계 이동의 눈금(없으면 null).
//   true  — 받는다(이동이 없었거나, 이동한 지 충분히 지났거나, 판정할 수 없다)
//   false — 삼킨다(화면이 방금 바뀌었다 — 이 누름은 앞 화면을 겨눈 것이다)
export function tapSettled(movedTick, tick, settleMs = EUM_SETTLE_MS) {
  const from = typeof movedTick === 'number' && Number.isFinite(movedTick) ? movedTick : null;
  const now = typeof tick === 'number' && Number.isFinite(tick) ? tick : null;
  // `Number(Symbol)` 은 **throw 한다** — 누름 판정이 던지면 그 단추가 그 자리에서 죽는다
  // (parseStep·lib/eumCountdown 의 num 과 같은 이유). 수로 바꿀 수 있는 종류에만 건다.
  const span = typeof settleMs === 'number' ? settleMs : NaN;
  // 모르면 통과 — 판정 실패가 누름을 삼키면 화면이 먹통으로 보인다(위 주석).
  if (from === null || now === null || !Number.isFinite(span) || span <= 0) return true;
  const elapsed = now - from;
  // 눈금이 뒤로 갔다(눈금 교체 등) → 얼마나 지났는지 알 수 없으므로 통과시킨다.
  if (elapsed < 0) return true;
  return elapsed >= span;
}

// ── 그 눈금을 적어야 하는 전환이 **하나 더** 있었다 ────────────────────────
//
// 고친 결함: 눈금을 적는 자리는 둘이었다 — 단계 이동(`go`)과 「다시 시도」로 되살아난 마운트.
// 그 둘을 고른 가름선은 「그 화면 전환이 **누름의 결과**인가」이고, 그때 popstate 는 "겨눈
// 손이 없다" 는 사유로 빠졌다. 그 사유는 **브라우저가 일으킨** 뒤로가기(제스처·하드웨어 단추·
// 주소창)에는 맞지만, **우리 링크를 눌러서** 일어난 되돌아가기에는 맞지 않는다 —
// 「앞 화면으로」·「다시 고르기」가 바로 그것이고, 그 누름은 `history.back()` 을 거쳐 popstate
// 로 돌아온다. 우리가 세운 가름선 쪽에서 보면 적어야 하는 전환인데 적지 않고 있었다
// (20회차가 "마운트에는 겨눈 손이 없다" 를 한 마운트에서 뒤집은 것과 **같은 모양**이고,
//  이번에도 그 사실은 이미 화면이 들고 있었다 — 아래 `pendingDepth`).
//
// 무엇이 일어나나: 그 링크는 이 화면의 **유일한 되돌리기 수단**이라 손이 떨려 두 번 눌리는
// 것이 흔하고(14회차가 `backFromRef` 를 둔 이유가 그것이다), 두 번째 탭이 도착할 때 화면은
// 이미 **앞 단계**다. 그 자리에 있는 것은 다른 뜻의 조작 요소다 —
//   · 2단계의 「앞 화면으로」 → 1단계. 그 위쪽은 **활동 선택지 네 개**이고, 두 번째 탭이
//     거기 떨어지면 읽지 않은 활동이 골라져 화면이 **다시 2단계로** 간다. 되돌아가려고 누른
//     손이 앞으로 가 있고, 어르신에게는 「눌렀는데 또 넘어갔다」로 보인다(그 다음에 할 일은
//     또 되돌아가기이고, 그 누름도 같은 길을 탄다).
//   · 3단계의 「다시 고르기」 → 2단계. 요약·주버튼이 사라진 만큼 선택지가 위로 올라오므로
//     그 자리에 **시간대 선택지**가 올 수 있고(실렌더로 확인하지 않았다), 그러면 읽지 않은
//     시간대가 골라진 채 확인 화면이 다시 열려 화면이 「이대로 신청할까요?」라고 묻는다.
// 20회차가 막은 것과 같은 사고이고 방향만 반대다(앞으로 가는 전환 ↔ 되돌아가는 전환).
//
// 가름선은 그대로 둔다 — 적는 것은 **우리가 요청한** 되돌아가기뿐이다. 그 사실은 화면에 이미
// 있다: `backFromRef` 는 14회차가 같은 자리의 두 번째 누름을 삼키려고 적어 두는 깊이이고,
// 요청한 traversal 이 도착하면 비운다. 적혀 있지 않은 popstate(브라우저가 일으킨 것·앞으로
// 가기)는 **모르는 쪽**이므로 적지 않는다 — 모를 때는 통과시킨다(tapSettled 와 같은 방향).
export function popFromTap(pendingDepth) {
  return Number.isInteger(pendingDepth);
}
